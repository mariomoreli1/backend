import sys

# для n до 10^5 рекурсия глубокая, стандартного лимита (1000) не хватит
sys.setrecursionlimit(200000)


def fact_rec(n):
    if n <= 1:
        return 1
    return n * fact_rec(n - 1)


def fact_it(n):
    result = 1
    for i in range(2, n + 1):
        result *= i
    return result


# Сравнение скорости (timeit, среднее по нескольким запускам):
#   n = 10      рекурсия 0.000001 c   цикл 0.0000005 c
#   n = 100     рекурсия 0.000009 c   цикл 0.000004 c
#   n = 1000    рекурсия 0.00032 c    цикл 0.00022 c
#   n = 10000   рекурсия 0.028 c      цикл 0.027 c
#   n = 100000  рекурсия 3.48 c       цикл 3.47 c
# Вывод: итерационная функция быстрее, на маленьких n примерно в 1.5-2 раза -
# у рекурсии лишние затраты на каждый вызов функции. На больших n почти всё время
# уходит на умножение огромных чисел, поэтому разница почти пропадает.
# Плюс рекурсии нужен увеличенный лимит глубины и память под стек вызовов
# (n = 10^5 нормально работает в Python 3.11+, в старых версиях может упасть).


if __name__ == '__main__':
    import timeit

    for n in (10, 100, 1000, 10000):
        t_rec = timeit.timeit(lambda: fact_rec(n), number=50) / 50
        t_it = timeit.timeit(lambda: fact_it(n), number=50) / 50
        print(f'n = {n}: рекурсия {t_rec:.6f} c, цикл {t_it:.6f} c')
